#!/usr/bin/env node
// Copies the shared rules the edge functions need from packages/shared/src into
// supabase/functions/_shared/shared, so they live once (CLAUDE.md "Shared rules live once") and the
// Deno bundle has no path outside supabase/functions. Starts from the entry modules below, follows
// every relative import, and rewrites each specifier to the file with its .ts extension (Deno
// resolves no bare directories). `zod` stays a bare import; supabase/functions/deno.json pins it.
//
// Usage: node scripts/supabase/sync-shared.mjs          write the copies
//        node scripts/supabase/sync-shared.mjs --check  exit 1 if a copy is missing, stale or extra
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const SRC = path.join(ROOT, 'packages/shared/src');
export const OUT = path.join(ROOT, 'supabase/functions/_shared/shared');
export const ENTRIES = [
  'api/index.ts',
  'widget-state/index.ts',
  'catalog/index.ts',
  'limits/index.ts',
];

const HEADER =
  '// GENERATED by scripts/supabase/sync-shared.mjs from packages/shared/src. Do not edit.\n' +
  '// deno-lint-ignore-file\n';
const SPEC = /(\bfrom\s+)(['"])(\.{1,2}\/[^'"]+)\2/g;

function resolveSpec(fromFile, spec) {
  const base = path.resolve(path.dirname(fromFile), spec);
  for (const candidate of [base, `${base}.ts`, path.join(base, 'index.ts')]) {
    if (existsSync(candidate) && statSync(candidate).isFile()) return candidate;
  }
  throw new Error(`cannot resolve ${spec} from ${path.relative(ROOT, fromFile)}`);
}

/** Every file the entries need, with its rewritten text, keyed by path relative to src. */
export function collect(src = SRC, entries = ENTRIES) {
  const out = new Map();
  const queue = entries.map((e) => path.join(src, e));
  while (queue.length) {
    const file = queue.shift();
    const rel = path.relative(src, file);
    if (out.has(rel)) continue;
    if (rel.startsWith('..')) throw new Error(`${rel} is outside packages/shared/src`);
    const text = readFileSync(file, 'utf8');
    const rewritten = text.replace(SPEC, (_m, from, q, spec) => {
      const target = resolveSpec(file, spec);
      queue.push(target);
      let r = path.relative(path.dirname(file), target).split(path.sep).join('/');
      if (!r.startsWith('.')) r = `./${r}`;
      return `${from}${q}${r}${q}`;
    });
    out.set(rel, HEADER + rewritten);
  }
  return out;
}

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  const files = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) files.push(...listFiles(p));
    else files.push(p);
  }
  return files;
}

/** Differences between the wanted copies and what is on disk. */
export function diff(wanted = collect(), outDir = OUT) {
  const problems = [];
  for (const [rel, text] of wanted) {
    const p = path.join(outDir, rel);
    if (!existsSync(p)) problems.push(`missing ${rel}`);
    else if (readFileSync(p, 'utf8') !== text) problems.push(`stale ${rel}`);
  }
  for (const p of listFiles(outDir)) {
    const rel = path.relative(outDir, p);
    if (!wanted.has(rel)) problems.push(`extra ${rel}`);
  }
  return problems;
}

function main() {
  const wanted = collect();
  if (process.argv.includes('--check')) {
    const problems = diff(wanted);
    if (problems.length) {
      console.error(
        `supabase/functions/_shared/shared is out of date (run node scripts/supabase/sync-shared.mjs):`,
      );
      for (const p of problems) console.error(`  ${p}`);
      process.exit(1);
    }
    console.log(`sync-shared: ${wanted.size} file(s) up to date`);
    return;
  }
  rmSync(OUT, { recursive: true, force: true });
  for (const [rel, text] of wanted) {
    const p = path.join(OUT, rel);
    mkdirSync(path.dirname(p), { recursive: true });
    writeFileSync(p, text);
  }
  console.log(`sync-shared: wrote ${wanted.size} file(s) to ${path.relative(ROOT, OUT)}`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
