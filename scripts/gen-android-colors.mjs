#!/usr/bin/env node
// Android colour resources for the native widget, from the app's design tokens.
//
//   node scripts/gen-android-colors.mjs           write values/clink_colors.xml and values-night/clink_colors.xml
//   node scripts/gen-android-colors.mjs --check   exit 1 if either file is out of date
//
// Source of truth: app/src/ui/theme/colors.ts and categories.ts (DESIGN.md 2.1, 2.2), which the app
// already reads. Light values go to values/, dark values to values-night/, so the launcher picks
// the right one from the system theme on every Android version (DESIGN.md 5.1 "Theme").
import { existsSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

import { REPO_ROOT, writeOrCheck } from '../packages/shared/tools/copy-md.mjs';

const COLORS_TS = join(REPO_ROOT, 'app/src/ui/theme/colors.ts');
const CATEGORIES_TS = join(REPO_ROOT, 'app/src/ui/theme/categories.ts');
const RES = join(REPO_ROOT, 'app/assets/native/android/res');

/** Core tokens the widget draws with (DESIGN.md 5). */
export const CORE_TOKENS = [
  'surfaceBase',
  'surfaceRaised',
  'surfaceSunk',
  'inkPrimary',
  'inkSecondary',
  'inkTertiary',
  'lineHairline',
  'lineControl',
  'cobalt',
  'onCobalt',
  'cobaltTint',
  'danger',
  'onDanger',
  'scrimPhoto',
];
export const CATEGORIES = ['coffee', 'matcha', 'tea', 'smoothie_juice', 'water'];
const CATEGORY_ROLES = ['solid', 'onSolid', 'tint', 'ink'];

/** The text between `${name}: {` and its matching `}`. */
function block(src, name, from = 0) {
  const start = src.indexOf(`${name}: {`, from);
  if (start === -1) throw new Error(`gen-android-colors: no "${name}" block`);
  let depth = 0;
  for (let i = src.indexOf('{', start); i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}' && --depth === 0) return src.slice(start, i + 1);
  }
  throw new Error(`gen-android-colors: unbalanced "${name}" block`);
}

function hexes(text) {
  const out = {};
  for (const m of text.matchAll(/(\w+): '(#[0-9A-Fa-f]{6})'/g)) out[m[1]] = m[2].toUpperCase();
  return out;
}

export function readTokens() {
  const core = readFileSync(COLORS_TS, 'utf8');
  const cats = readFileSync(CATEGORIES_TS, 'utf8');
  const tokens = {};
  for (const mode of ['light', 'dark']) {
    const c = hexes(block(core, mode, core.indexOf('export const colors')));
    const k = block(cats, mode, cats.indexOf('export const categoryColors'));
    const t = {};
    for (const name of CORE_TOKENS) {
      if (!c[name]) throw new Error(`gen-android-colors: ${mode}.${name} missing in colors.ts`);
      t[name] = c[name];
    }
    for (const cat of CATEGORIES) {
      const line = k.match(new RegExp(`\\b${cat}: \\{([^}]*)\\}`));
      if (!line) throw new Error(`gen-android-colors: ${mode}.${cat} missing in categories.ts`);
      const v = hexes(line[1]);
      for (const role of CATEGORY_ROLES) {
        if (!v[role]) throw new Error(`gen-android-colors: ${mode}.${cat}.${role} missing`);
        t[`${cat}_${role}`] = v[role];
      }
    }
    tokens[mode] = t;
  }
  return tokens;
}

export function resourceName(token) {
  return `clink_${token.replace(/([a-z])([A-Z])/g, '$1_$2').toLowerCase()}`;
}

export function buildXml(values, mode) {
  const lines = Object.entries(values).map(
    ([k, v]) => `    <color name="${resourceName(k)}">${v}</color>`,
  );
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- GENERATED by scripts/gen-android-colors.mjs from app/src/ui/theme (${mode}). Do not edit. -->`,
    '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="UnusedResources">',
    ...lines,
    '</resources>',
    '',
  ].join('\n');
}

// ---------------------------------------------------------------------------------------------
// Background shapes (DESIGN.md 2.6, 5.1). They reference the colour resources above, so night
// mode switches with no code. Containers and inner tiles use the system widget radii on
// Android 12+ (drawable-v31) and 16 dp / 8 dp before. Glance's cornerRadius needs Android 12, so
// every rounded background comes from these drawables instead, on every version.

const FLARE_CATS = CATEGORIES.filter((c) => c !== 'water');
const c = (token) => `@color/${resourceName(token)}`;

const RADIUS = {
  container: { base: '16dp', v31: '@android:dimen/system_app_widget_background_radius' },
  inner: { base: '8dp', v31: '@android:dimen/system_app_widget_inner_radius' },
  pill: { base: '999dp', v31: null },
};

function rimmed(body, rim, rimDp, radius) {
  // A rim is a band along the top inside edge, inside the container outline (DESIGN.md
  // 2.6): the rim colour fills the rounded shape and the body covers all but its top band.
  return [
    '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">',
    '    <item>',
    '        <shape android:shape="rectangle">',
    `            <solid android:color="${c(rim)}" />`,
    `            <corners android:radius="${radius}" />`,
    '        </shape>',
    '    </item>',
    `    <item android:top="${rimDp}">`,
    '        <shape android:shape="rectangle">',
    `            <solid android:color="${c(body)}" />`,
    // Same radius as the outer shape: the band follows the corner curve and thins out down
    // the sides, like the lip of an enamel mug. Square corners here would poke past the outline.
    `            <corners android:radius="${radius}" />`,
    '        </shape>',
    '    </item>',
    '</layer-list>',
  ];
}

function plain(fill, radius, stroke) {
  return [
    '<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">',
    fill
      ? `    <solid android:color="${c(fill)}" />`
      : '    <solid android:color="@android:color/transparent" />',
    ...(stroke ? [`    <stroke android:width="1.5dp" android:color="${c(stroke)}" />`] : []),
    `    <corners android:radius="${radius}" />`,
    '</shape>',
  ];
}

/** [name, radius kind, (radius) => xml lines] */
export function shapeList() {
  const list = [
    ['clink_bg_widget_idle', 'container', (r) => rimmed('surfaceBase', 'cobalt', '4dp', r)],
  ];
  for (const cat of FLARE_CATS) {
    list.push([
      `clink_bg_widget_live_${cat}`,
      'container',
      (r) => rimmed(`${cat}_solid`, `${cat}_tint`, '4dp', r),
    ]);
    list.push([
      `clink_bg_widget_friend_${cat}`,
      'container',
      (r) => rimmed(`${cat}_tint`, `${cat}_ink`, '4dp', r),
    ]);
    list.push([`clink_bg_pill_${cat}_solid`, 'pill', (r) => plain(`${cat}_solid`, r)]);
    list.push([`clink_bg_pill_${cat}_tint`, 'pill', (r) => plain(`${cat}_tint`, r)]);
    list.push([`clink_bg_pill_outline_${cat}`, 'pill', (r) => plain(null, r, `${cat}_ink`)]);
    list.push([
      `clink_bg_cell_raised_${cat}`,
      'inner',
      (r) => rimmed('surfaceRaised', `${cat}_ink`, '2dp', r),
    ]);
  }
  for (const cat of CATEGORIES) {
    list.push([
      `clink_bg_cell_${cat}`,
      'inner',
      (r) => rimmed(`${cat}_tint`, `${cat}_ink`, '2dp', r),
    ]);
  }
  list.push(['clink_bg_pill_tonal', 'pill', (r) => plain('surfaceSunk', r)]);
  list.push(['clink_bg_pill_cobalt', 'pill', (r) => plain('cobalt', r)]);
  list.push(['clink_bg_pill_raised', 'pill', (r) => plain('surfaceRaised', r)]);
  list.push(['clink_bg_pill_ink', 'pill', (r) => plain('inkPrimary', r)]);
  list.push(['clink_bg_tile_sunk', 'inner', (r) => plain('surfaceSunk', r)]);
  return list;
}

const STATIC_SHAPES = {
  // Photo scrim (DESIGN.md 3.6): #0E141B from 0% at 45% of the height to 64% at the bottom.
  clink_bg_scrim: [
    '<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">',
    '    <gradient android:angle="270" android:type="linear" android:startColor="#000E141B"',
    '        android:centerY="0.45" android:centerColor="#000E141B" android:endColor="#A30E141B" />',
    '</shape>',
  ],
  // Avatar fallback (DESIGN.md 2.3 rule 6).
  clink_bg_avatar: [
    '<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="oval">',
    `    <solid android:color="${c('surfaceSunk')}" />`,
    `    <stroke android:width="1.5dp" android:color="${c('surfaceBase')}" />`,
    '</shape>',
  ],
};

export function buildShapes() {
  const head = (name) => [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- GENERATED by scripts/gen-android-colors.mjs (${name}). Do not edit. -->`,
  ];
  const out = [];
  for (const [name, kind, make] of shapeList()) {
    const r = RADIUS[kind];
    out.push([`drawable/${name}.xml`, [...head(name), ...make(r.base), ''].join('\n')]);
    if (r.v31)
      out.push([`drawable-v31/${name}.xml`, [...head(name), ...make(r.v31), ''].join('\n')]);
  }
  for (const [name, lines] of Object.entries(STATIC_SHAPES)) {
    out.push([`drawable/${name}.xml`, [...head(name), ...lines, ''].join('\n')]);
  }
  return out;
}

async function main() {
  const check = process.argv.includes('--check');
  const tokens = readTokens();
  let stale = false;
  const shapes = buildShapes();
  const want = new Set(shapes.map(([p]) => p));
  for (const [rel, xml] of shapes) {
    const r = await writeOrCheck(join(RES, rel), xml, check);
    if (r.stale) {
      console.error(`${rel} is out of date. Run: node scripts/gen-android-colors.mjs`);
      stale = true;
    }
  }
  for (const dir of ['drawable', 'drawable-v31']) {
    const full = join(RES, dir);
    if (!existsSync(full)) continue;
    for (const f of readdirSync(full).filter((x) => x.startsWith('clink_bg_'))) {
      if (want.has(`${dir}/${f}`)) continue;
      if (check) {
        console.error(`extra: ${dir}/${f}`);
        stale = true;
      } else rmSync(join(full, f));
    }
  }
  for (const [mode, dir] of [
    ['light', 'values'],
    ['dark', 'values-night'],
  ]) {
    const r = await writeOrCheck(
      join(RES, dir, 'clink_colors.xml'),
      buildXml(tokens[mode], mode),
      check,
    );
    if (r.stale) {
      console.error(`${r.path} is out of date. Run: node scripts/gen-android-colors.mjs`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log(check ? 'android colours up to date' : 'wrote android colours');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  await main();
}
