#!/usr/bin/env node
// Android string resources for the native widget, from the COPY.md string table.
//
//   node scripts/gen-android-strings.mjs           write app/assets/native/android/res/values/clink_strings.xml
//   node scripts/gen-android-strings.mjs --check   exit 1 if the file is out of date (CI drift check)
//
// Input is packages/shared/generated/strings.json (made from docs/COPY.md by gen-strings.mjs), so
// Kotlin reads exactly the text the app reads. Only the key families the widget draws are copied
// (WIDGET_PREFIXES). Each key becomes `clink_` + the key with dots as underscores. The value is the
// raw ICU message; Kotlin formats it with its port of packages/shared/src/strings/icu.ts (Icu.kt).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

import { REPO_ROOT, writeOrCheck } from '../packages/shared/tools/copy-md.mjs';

export const STRINGS_JSON = join(REPO_ROOT, 'packages/shared/generated/strings.json');
export const OUT = join(REPO_ROOT, 'app/assets/native/android/res/values/clink_strings.xml');

/** Key families the Android widget uses (COPY.md 4.26, 4.27, 6, plus category and size words). */
export const WIDGET_PREFIXES = ['ws.', 'wm.', 'a11y.w.', 'fmt.', 'cat.', 'set.widgets.size.'];

export function resourceName(key) {
  const name = `clink_${key.replace(/\./g, '_')}`;
  if (!/^[a-z][a-z0-9_]*$/.test(name)) {
    throw new Error(`gen-android-strings: key "${key}" does not make a resource name (${name})`);
  }
  return name;
}

/** Escapes text for an Android <string> value (aapt2 rules). */
export function escapeAndroid(text) {
  let out = text
    .replace(/\\/g, '\\\\')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '\\"')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n');
  if (/^[@?]/.test(out)) out = `\\${out}`;
  return out;
}

export function pickWidgetStrings(strings) {
  return Object.keys(strings)
    .filter((k) => WIDGET_PREFIXES.some((p) => k.startsWith(p)))
    .sort()
    .map((k) => [k, strings[k]]);
}

export function buildXml(strings) {
  const entries = pickWidgetStrings(strings);
  const seen = new Map();
  const lines = entries.map(([key, text]) => {
    const name = resourceName(key);
    const prev = seen.get(name);
    if (prev) throw new Error(`gen-android-strings: "${key}" and "${prev}" both map to ${name}`);
    seen.set(name, key);
    // formatted="false": the values are ICU messages, never printf patterns.
    return `    <string name="${name}" formatted="false">${escapeAndroid(text)}</string>`;
  });
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- GENERATED by scripts/gen-android-strings.mjs from docs/COPY.md (via',
    '     packages/shared/generated/strings.json). Do not edit; change COPY.md and regenerate. -->',
    '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="UnusedResources,TypographyEllipsis">',
    ...lines,
    '</resources>',
    '',
  ].join('\n');
}

async function main() {
  const check = process.argv.includes('--check');
  const { strings } = JSON.parse(readFileSync(STRINGS_JSON, 'utf8'));
  const xml = buildXml(strings);
  const r = await writeOrCheck(OUT, xml, check);
  if (r.stale) {
    console.error(`${OUT} is out of date. Run: node scripts/gen-android-strings.mjs`);
    process.exit(1);
  }
  const n = pickWidgetStrings(strings).length;
  console.log(check ? `android strings up to date (${n})` : `wrote ${n} strings to ${OUT}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  await main();
}
