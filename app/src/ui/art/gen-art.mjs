#!/usr/bin/env node
// Bundles the SVG masters in app/assets/art into art.generated.ts, so the app can draw them with
// react-native-svg and apply the dark-mode swaps from DESIGN.md 3.5 at runtime (art.ts).
// Run: node app/src/ui/art/gen-art.mjs        (writes)
//      node app/src/ui/art/gen-art.mjs --check (fails if the file is stale; run by art.test.ts)
// The masters stay the source of truth; this file only copies them, minus comments.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const artDir = path.resolve(here, '../../../assets/art');
const outFile = path.join(here, 'art.generated.ts');

function clean(svg) {
  return svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/>\s+</g, '><')
    .replace(/\s+/g, ' ')
    .trim();
}

function readDir(sub, filter = () => true) {
  const dir = path.join(artDir, sub);
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.svg') && filter(f))
    .sort()
    .map((f) => [f.replace(/\.svg$/, ''), clean(fs.readFileSync(path.join(dir, f), 'utf8'))]);
}

function block(name, entries) {
  const lines = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  return `export const ${name}: Record<string, string> = {\n${lines.join('\n')}\n};\n`;
}

const icons = readDir('icons');
const iconsS = icons.filter(([k]) => k.endsWith('.24')).map(([k, v]) => [k.slice(0, -3), v]);
const iconsL = icons.filter(([k]) => k.endsWith('.64')).map(([k, v]) => [k.slice(0, -3), v]);
const brand = readDir('brand', (f) =>
  ['wordmark.svg', 'wordmark-dark.svg', 'mark.svg', 'mark-small.svg', 'app-icon.svg'].includes(f),
);

const raw = [
  '// GENERATED by app/src/ui/art/gen-art.mjs from app/assets/art. Do not edit.',
  '// Re-run the script after the art changes; art.test.ts fails when this file is stale.',
  '',
  block('HEROES', readDir('heroes')),
  block('GLYPHS', readDir('glyphs')),
  block('ICONS_S', iconsS),
  block('ICONS_L', iconsL),
  block('BRAND', brand),
].join('\n');

const prettier = await import('prettier');
const options = (await prettier.resolveConfig(outFile)) ?? {};
const out = await prettier.format(raw, { ...options, filepath: outFile });

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (current !== out) {
    console.error('art.generated.ts is stale. Run: node app/src/ui/art/gen-art.mjs');
    process.exit(1);
  }
} else {
  fs.writeFileSync(outFile, out);
  console.log(`Wrote ${path.relative(process.cwd(), outFile)} (${out.length} bytes)`);
}
